#!/usr/bin/env python3
"""Writes docs/asset-budget.md from asset-manifests/cost-ledger.jsonl + asset-manifest.json (actual API spend)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ledger = [json.loads(l) for l in (ROOT / "asset-manifests/cost-ledger.jsonl").read_text().splitlines() if l.strip()]
manifest = json.loads((ROOT / "asset-manifests/asset-manifest.json").read_text())["assets"]
budget = json.loads((ROOT / "asset-pipeline/budget.json").read_text())
settled = {}
for e in ledger:
    if e["type"] == "settle":
        settled[e["category"]] = settled.get(e["category"], 0) + e["amount"]
calls = sum(1 for e in ledger if e["type"] == "settle")
released = sum(1 for e in ledger if e["type"] == "release")
lines = ["# AI asset budget (actual spend)", "",
         "Generated by `tools/cost_report.py` from the pipeline ledger. Costs are computed from the token usage returned by the",
         "OpenAI API at the configured per-token rates (conservative: all output tokens billed at the image-output rate).", "",
         "| Budget | Spent | Cap | Remaining |", "|---|---|---|---|"]
for cat, cap in budget["categories"].items():
    s = settled.get(cat, 0)
    lines.append(f"| {cat} | ${s:.4f} | ${cap:.2f} | ${cap - s:.4f} |")
tot = sum(settled.values())
lines += [f"| **total** | **${tot:.4f}** | **${budget['totalCap']:.2f}** | **${budget['totalCap'] - tot:.4f}** |", "",
          f"Billed API calls: {calls}. Calls refused before billing (released reservations): {released}.", "",
          "## Assets", "", "| Asset | Category | Model | Size | Quality | Cost | Status |", "|---|---|---|---|---|---|---|"]
for aid, a in sorted(manifest.items()):
    lines.append(f"| {aid} | {a['category']} | {a['model']} | {a['size']} | {a['quality']} | ${a['generationCost']:.4f} | {a['status']} |")
pets = [a for a in manifest.values() if a["category"] == "pet"]
avg = sum(a["generationCost"] for a in pets) / max(1, len(pets))
lines += ["", "## Projection for the full Pet catalog", "",
          f"Average actual cost per pet artwork: ${avg:.4f}. Remaining 190 pets ≈ ${avg * 190:.2f}"
          f" (+10% regeneration allowance ≈ ${avg * 190 * 1.1:.2f}) against ${budget['categories']['pet'] - settled.get('pet', 0):.2f} left in the pet budget."]
(ROOT / "docs/asset-budget.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[6:10] + lines[-1:]))
